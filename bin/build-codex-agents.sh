#!/bin/sh
# Build codex/.codex/AGENTS.md from the Claude sources.
#
# Claude Code auto-loads ~/.claude/CLAUDE.md and every file in ~/.claude/rules/.
# Codex has no rules/ directory: it reads a single global AGENTS.md from
# $CODEX_HOME. So the Claude sources are the canonical copy and this script
# flattens them into the one file Codex reads.
#
# Re-run after editing CLAUDE.md or anything under claude/.claude/rules/.
#
# Deliberately excludes work-dotfiles rules (brazil.md, amazon-*.md,
# codepipeline-research.md). Those are Amazon-internal and do not belong in a
# personal repo that gets pushed to GitHub. To make them apply in Codex, add an
# equivalent step to work-dotfiles and append to $CODEX_HOME/AGENTS.md there.

set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
src_md="$root/claude/.claude/CLAUDE.md"
src_rules="$root/claude/.claude/rules"
out="$root/codex/.codex/AGENTS.md"

[ -f "$src_md" ] || { echo "missing $src_md" >&2; exit 1; }
[ -d "$src_rules" ] || { echo "missing $src_rules" >&2; exit 1; }

mkdir -p "$(dirname -- "$out")"
tmp="$out.tmp$$"

{
	printf '%s\n' '<!-- GENERATED by bin/build-codex-agents.sh. Do not edit by hand. -->'
	printf '%s\n' '<!-- Sources: claude/.claude/CLAUDE.md and claude/.claude/rules/*.md -->'
	printf '\n'
	cat -- "$src_md"

	# Sorted so the output is reproducible regardless of readdir order.
	for f in $(ls -- "$src_rules" | grep '\.md$' | sort); do
		printf '\n'
		# Only title the section when the rule doesn't already open with a
		# heading of its own, so files like handoff-offer.md aren't double-titled.
		case $(head -n 1 -- "$src_rules/$f") in
		'#'*) ;;
		*) printf '# %s\n\n' "${f%.md}" ;;
		esac
		cat -- "$src_rules/$f"
	done
} >"$tmp"

mv -- "$tmp" "$out"
echo "wrote $out ($(wc -c <"$out" | tr -d ' ') bytes, $(ls -- "$src_rules" | grep -c '\.md$') rules)"
